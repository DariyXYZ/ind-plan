# Планировки для тестов 06, 07, 08 (по 4 варианта). мм, оси, Y вниз.
# Комната = прямоугольники по осям; перегородки 100 мм строятся по границам комнат автоматически.
# Дверь: (x, y на оси стены, ширина, комната, куда открывается / где едет полотно, петли 's'|'e'[, 'sl' — раздвижная]).
# Мебель: (код, x, y базы = середина задней грани, поворот[, длина[, глубина]]) — длина/глубина у параметрических (шкаф, столешница, ванна).
# Ряды вдоль стен собираются помощниками N/S/W/E встык — без щелей.
W0 = {'bed': 1600, 'sbed': 900, 'sofa': 2200, 'dining': 1200, 'desk': 1200, 'coffee': 900, 'wardrobe': 1800, 'base': 600, 'hob': 600,
      'sink': 600, 'fridge': 600, 'washer': 600, 'wc': 380, 'bidet': 360, 'basin': 500, 'bath': 1700, 'shower': 900}

def _run(r, axis, fixed, start, items):
    out, p = [], start
    for it in items:
        if isinstance(it, str): it = (it,)
        k = it[0]; w = it[1] if len(it) > 1 else None; d = it[2] if len(it) > 2 else None
        L_ = w or W0[k]; c = p + L_ / 2; p += L_
        x, y = (c, fixed) if axis == 'x' else (fixed, c)
        out.append((k, x, y, r) + ((w or 0, d or 0) if (w or d) else ()))
    return out
N = lambda y, x0, items: _run(0, 'x', y, x0, items)      # у стены сверху, тело вниз
S = lambda y, x0, items: _run(180, 'x', y, x0, items)    # у стены снизу, тело вверх
W = lambda x, y0, items: _run(-90, 'y', x, y0, items)    # у стены слева, тело вправо
E = lambda x, y0, items: _run(90, 'y', x, y0, items)     # у стены справа, тело влево

